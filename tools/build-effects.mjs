// Rebuild the three offline BookWiz effects. Third-party source: vendor/pixelfx/LICENSE.
import {mkdir,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
import {createFrame,clearFrame,createFx,composite} from './vendor/pixelfx/src/core/index.js';
import {encodePNG} from './vendor/pixelfx/tools/lib/png.mjs';
import * as paper from './vendor/pixelfx/src/fx/ui/confetti.js';
import * as ripple from './vendor/pixelfx/src/fx/water/ripples.js';
import * as glint from './vendor/pixelfx/src/fx/pickups/collect-burst.js';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const directory=resolve(root,'dist/assets/effects');await mkdir(directory,{recursive:true});
const effects=[
 {id:'paper',label:'A page worth celebrating',description:'A short shower of paper for a completed writing session.',module:paper,palette:['#214b63','#608d9a','#e7c7a5','#efad91','#f7edda','#abc4ba','#b5aa96']},
 {id:'ripple',label:'A little room to think',description:'One quiet ripple, played only when you ask.',module:ripple,palette:['#183849','#2e5d70','#70969e','#aac7bf','#eff0df']},
 {id:'glint',label:'A finished thought',description:'A brief ink-and-gold punctuation mark.',module:glint,palette:['#244956','#678c8d','#bea578','#e6cba0','#fff2d8']},
];
const manifest=[];
for(const effect of effects){
 const mod=effect.module,meta=mod.meta,[width,height]=meta.size,fps=20;
 const frames=Math.round(meta.duration*fps)+1,columns=Math.ceil(Math.sqrt(frames*height/width)),rows=Math.ceil(frames/columns);
 const atlas=new Uint8ClampedArray(width*columns*height*rows*4),frame=createFrame(width,height);
 const instance=createFx(mod,{x:meta.origin[0],y:meta.origin[1],palette:effect.palette,seed:11,light:.35});
 for(let i=0;i<frames;i++){
  if(i)instance.update(1/fps);clearFrame(frame);instance.draw(frame);
  const pixels=composite(frame,new Uint8ClampedArray(width*height*4),null),left=(i%columns)*width,top=Math.floor(i/columns)*height;
  for(let y=0;y<height;y++)atlas.set(pixels.subarray(y*width*4,(y+1)*width*4),((top+y)*columns*width+left)*4);
 }
 await writeFile(resolve(directory,effect.id+'.png'),encodePNG(width*columns,height*rows,atlas));
 manifest.push({id:effect.id,label:effect.label,description:effect.description,src:'assets/effects/'+effect.id+'.png',frameWidth:width,frameHeight:height,frames,columns,fps,duration:frames/fps});
}
await writeFile(resolve(directory,'manifest.json'),JSON.stringify({format:1,source:'https://github.com/patch-gg/pixelfx',license:'MIT',effects:manifest},null,2)+'\n');
await writeFile(resolve(directory,'catalog.js'),'// Generated by tools/build-effects.mjs.\nexport const pixelEffects='+JSON.stringify(manifest,null,2)+';\n');
console.log('Rebuilt '+manifest.length+' local pixel effects.');
